/* Vercel build: copy the static app into public/ and write js/config.js from
   environment variables. No secrets belong here — everything in public/ is
   downloadable by anyone.

   SMIVAI_API_BASE_URL      https URL of the Render API, e.g. https://smivai-api.onrender.com
   SMIVAI_FULL_SERVER_MODE  "1" = every role signs in through the server
                            (default: only donors and charity staff do;
                            patients, caregivers and doctors stay on the device) */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'public');
const SHIP = ['index.html', 'css', 'js', 'assets'];   // backend/, tests/, docs/ are never published

function apiBase(raw) {
  const v = String(raw || '').trim().replace(/\/+$/, '');
  if (!v) return '';
  let u;
  try { u = new URL(v); } catch (e) { throw new Error('SMIVAI_API_BASE_URL is not a valid URL: ' + v); }
  const local = /^(localhost|127\.0\.0\.1)$/.test(u.hostname);
  if (u.protocol !== 'https:' && !local) throw new Error('SMIVAI_API_BASE_URL must use https:// — ' + v);
  if (u.pathname !== '/' || u.search || u.hash) throw new Error('SMIVAI_API_BASE_URL must be the server root, without a path — ' + v);
  return u.origin;
}

function configJs(env) {
  const cfg = { API_BASE_URL: apiBase(env.SMIVAI_API_BASE_URL), FULL_SERVER_MODE: env.SMIVAI_FULL_SERVER_MODE === '1' };
  return '/* Generated by scripts/build.js at ' + new Date().toISOString() + ' — do not edit. */\n' +
    'window.SMIVAI_ENV = ' + JSON.stringify(cfg) + ';\n';
}

function build(env) {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT);
  for (const p of SHIP) fs.cpSync(path.join(ROOT, p), path.join(OUT, p), { recursive: true });
  const js = configJs(env);
  fs.writeFileSync(path.join(OUT, 'js', 'config.js'), js);
  return js;
}

if (require.main === module) {
  const js = build(process.env);
  console.log('[smivai] built public/ —', js.split('\n')[1]);
  if (!/API_BASE_URL":"http/.test(js)) console.warn('[smivai] SMIVAI_API_BASE_URL is not set: donor and staff sign-in will say the server is not connected.');
}
module.exports = { apiBase, configJs };
